/**
 * FUNÇÃO AUXILIAR: Obter mídias de uma aula específica
 * @param {number} numeroAula - Número da aula (1-16)
 * @returns {object} Objeto com mídias da aula
 */
function obterMidiasAula(numeroAula) {
  const aula = MIDIAS[`aula_${numeroAula.toString().padStart(2, '0')}`];
  return aula || null;
}

/**
 * FUNÇÃO AUXILIAR: Listar todas as aulas
 * @returns {array} Array com títulos de todas as aulas
 */
function listarTodasAulas() {
  return Object.keys(MIDIAS).map((key, index) => {
    return {
      numero: MIDIAS[key].numero,
      titulo: MIDIAS[key].titulo
    };
  });
}

/**
 * FUNÇÃO AUXILIAR: Contar total de recursos
 * @returns {object} Contagem de cada tipo de mídia
 */
function contarRecursos() {
  let total = {
    imagens: 0,
    videos: 0,
    recursos: 0
  };

  Object.values(MIDIAS).forEach(aula => {
    if (aula.imagens) total.imagens += aula.imagens.length;
    if (aula.videos) total.videos += aula.videos.length;
    if (aula.recursos) total.recursos += aula.recursos.length;
  });

  return total;
}

// Garantir que MIDIAS é acessível globalmente no navegador
if (typeof window !== 'undefined') {
  window.MIDIAS = MIDIAS;
  window.obterMidiasAula = obterMidiasAula;
  window.listarTodasAulas = listarTodasAulas;
  window.contarRecursos = contarRecursos;
  console.log('MIDIAS carregado globalmente com sucesso!');
}

// Exportar para Node.js/módulos
if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    MIDIAS,
    obterMidiasAula,
    listarTodasAulas,
    contarRecursos
  };
}
